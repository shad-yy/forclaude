#!/usr/bin/env node
/**
 * Decide whether a change may ship to production without the owner.
 *
 * Tier A — content only. The routine may merge it to Version-3 itself, which
 *          deploys it, once every gate in the routine spec has passed.
 * Tier B — anything else. The routine opens a PR and the owner merges.
 *
 * Usage:
 *   node scripts/routine/tier.mjs [base]        # diff HEAD against base (default origin/Version-3)
 *   git diff --name-only ... | node scripts/routine/tier.mjs -
 *
 * Prints "A" or "B" on the first line, then any file that forced Tier B.
 * Exit 0 for A, 3 for B, so a shell step can branch on it.
 */
import { execFileSync } from "node:child_process"
import { readFileSync } from "node:fs"
import { pathToFileURL } from "node:url"

/** Paths a content-only change may touch. Everything else is Tier B. */
export const TIER_A = [
  /^content\/blog\/[a-z0-9][a-z0-9-]*\.mdx$/, // a post
  /^lib\/blog\/posts\.ts$/, // generated from content/blog by scripts/generate-posts.js
  /^public\/llms-full\.txt$/, // also generated by scripts/generate-posts.js from every post
  /^public\/blog\/[a-z0-9][a-z0-9-/]*\.(?:webp|avif|png|jpg|jpeg)$/, // a post's own images
  /^memory-bank\/ROUTINE-LOG\.md$/, // the routine's run log
]

export function classify(files) {
  const changed = files.map((f) => f.trim()).filter(Boolean)
  const blocking = changed.filter((f) => !TIER_A.some((re) => re.test(f)))
  return { tier: changed.length && blocking.length === 0 ? "A" : "B", blocking, changed }
}

function main(argv) {
  const files =
    argv[0] === "-"
      ? readFileSync(0, "utf8").split("\n")
      : execFileSync("git", ["diff", "--name-only", `${argv[0] ?? "origin/Version-3"}...HEAD`], { encoding: "utf8" }).split("\n")
  const r = classify(files)
  console.log(r.tier)
  if (!r.changed.length) console.log("(no changes — nothing to ship, treated as B)")
  for (const f of r.blocking) console.log(`  forces B: ${f}`)
  process.exit(r.tier === "A" ? 0 : 3)
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main(process.argv.slice(2))
